export const DICTS = { ru, en };
export const LANGS = [{ id: "ru", label: "Русский" }, { id: "en", label: "English" }];

// Plural forms: an array value picks its form by vars.n (ru: one / few / many, en: one / other).
const pluralRules = { ru: new Intl.PluralRules("ru"), en: new Intl.PluralRules("en") };
const FORM_INDEX = { ru: { one: 0, few: 1, many: 2, other: 1 }, en: { one: 0, other: 1 } };

export function translate(lang, key, vars) {
  const dict = DICTS[lang] || ru;
  let s = dict[key] ?? ru[key] ?? key;
  if (Array.isArray(s)) {
    const l = DICTS[lang] ? lang : "ru";
    const form = pluralRules[l].select(Number(vars?.n ?? 0));
    s = s[FORM_INDEX[l][form] ?? s.length - 1] ?? s[s.length - 1];
  }
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
